#!/usr/bin/env python3
"""Build nginx's deployed path inventory from its existing public route owners."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(globals().get('PROJECT_ROOT', Path.cwd()))
JAVA = ROOT / 'server/projects/profile/src/main/java'
OUTPUT = ROOT / 'server/docker/conf/nginx/conf/http/public-routes.map'
MAPPING = re.compile(r'@(Request|Get|Post|Put|Delete|Patch)Mapping\b(?:\s*\(([^)]*)\))?', re.S)


def inventory():
    sources = {path: path.read_text() for path in JAVA.rglob('*.java')}
    constants = {}
    for path, text in sources.items():
        for key, value in re.findall(r'\bString\s+(\w+)\s*=\s*"([^"]*)"', text):
            constants[path.stem + '.' + key] = value

    def paths(arguments):
        if not arguments or not arguments.strip():
            return ['']
        value = re.search(r'(?:^|,)\s*(?:path|value)\s*=\s*(\{[^}]*\}|"[^"]*"|[\w.]+)', arguments)
        value = value[1] if value else arguments.strip().split(',')[0]
        if value.startswith('"') or value.startswith('{'):
            return re.findall(r'"([^"]*)"', value)
        if value in constants:
            return [constants[value]]
        # A method can specify consumes/produces without a path.
        if re.match(r'(consumes|produces|method|headers|params)\s*=', value):
            return ['']
        raise ValueError('Unresolved public mapping: ' + value)

    routes = set()
    exact = set()
    for path, text in sources.items():
        if '@RestController' not in text and '@Controller' not in text:
            continue
        declaration = re.search(r'\bclass\s+\w+', text)
        if not declaration:
            continue
        before, after = text[:declaration.start()], text[declaration.end():]
        prefixes = [p for match in MAPPING.finditer(before) for p in paths(match[2])] or ['']
        for match in MAPPING.finditer(after):
            for prefix in prefixes:
                for suffix in paths(match[2]):
                    route = '/' + '/'.join(p.strip('/') for p in [prefix, suffix] if p.strip('/'))
                    route = '/api' + route
                    if not any(c in route for c in '{*'):
                        exact.add(route)
                        continue
                    escaped = re.escape(route)
                    escaped = re.sub(r'\\\{.*?\\\}', '[^/]+', escaped)
                    escaped = escaped.replace(r'\*\*', '.*').replace(r'\*', '[^/]*')
                    routes.add('^' + escaped + '$')
    # Angular's actual entry routes; lazy admin child routes own that subtree.
    angular = (ROOT / 'frontend/src/app/app.routes.ts').read_text()
    for route in re.findall(r"\bpath:\s*'([^']*)'", angular):
        if route == '**':
            continue
        if ':' not in route and route != 'admin':
            exact.add('/' + route)
            continue
        pattern = re.sub(r':\w+', '[^/]+', re.escape(route))
        routes.add('^/' + pattern + ('(?:/.*)?' if route == 'admin' else '') + '$')
    # Public nginx routes outside Java, and namespaces served as real static
    # files (their existing try_files rules still reject missing resources).
    routes.update([
        r'^/(?:index\.html|app-sw\.js|ngsw-worker\.js|safety-worker\.js|worker-basic\.min\.js|ngsw\.json|manifest\.webmanifest|app-version\.json|favicon\.ico|robots\.txt)$',
        r'^/[A-Za-z0-9_-]+\.(?:js|css|map|wasm)$',
        r'^/(?:assets|media)/[^\x00]*$',
        r'^/\.well-known/acme-challenge/[A-Za-z0-9_-]+$',
        r'^/(?:nginx-health|__landing-debug|api/runtime-status|api/runtime-status/events|api/health)$',
        r'^/api/(?:activities/chats/ws|admin/notifications/ws)$',
    ])
    routing = (ROOT / 'server/docker/conf/nginx/conf/http/routing.conf').read_text()
    for modifier, route in re.findall(r'location\s+(?:(=|\^~|~\*?|)\s+)?([^\s{]+)\s*\{', routing):
        if route == '/api/':
            continue
        if modifier == '=':
            exact.add(route)
        elif modifier.startswith('~'):
            routes.add(route)
        else:
            routes.add('^' + re.escape(route) + ('$' if modifier == '=' else '.*$'))
    exact.update('/' + route for route in ['index.html', 'app-sw.js', 'ngsw-worker.js', 'safety-worker.js', 'worker-basic.min.js', 'ngsw.json', 'manifest.webmanifest', 'app-version.json', 'favicon.ico', 'robots.txt', 'nginx-health', '__landing-debug', 'api/runtime-status', 'api/runtime-status/events', 'api/health', 'api/activities/chats/ws', 'api/admin/notifications/ws'])
    # Probes for dotfiles/executable server scripts are denied ahead of this map.
    return '# Generated by packaging/release/render-nginx-routes.py; do not edit.\n' + ''.join(json.dumps(route) + ' 1;\n' for route in sorted(exact)) + ''.join(
        json.dumps('~' + route) + ' 1;\n' for route in sorted(routes))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rendered = inventory()
    if args.check:
        if OUTPUT.read_text() != rendered:
            raise SystemExit('nginx URL inventory is stale; run packaging/release/render-nginx-routes.py')
    else:
        OUTPUT.write_text(rendered)
